package com.MessLoc.enums;

/**
 * Defines the user roles available within MessMate.
 * 
 * USER: Standard consumer searching, rating, reviewing messes, and managing favorites.
 * OWNER: Business owner managing mess details, pricing, daily menus, and facilities.
 * ADMIN: Platform administrator verifying owners, moderating reviews, and managing users.
 */
public enum Role {
    USER,
    OWNER,
    ADMIN
}
